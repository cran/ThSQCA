# Hand computation of solution coverage from a character solution (product terms).
.hand_covS <- function(terms, qd, y) {
  eval_term <- function(term) {
    parts <- strsplit(term, "\\*")[[1]]
    vals <- sapply(parts, function(p) {
      if (startsWith(p, "~")) 1 - qd[[substring(p, 2)]] else qd[[p]]
    })
    apply(as.matrix(vals), 1, min)
  }
  tm <- sapply(terms, eval_term)
  X <- apply(as.matrix(tm), 1, max)
  sum(pmin(X, y)) / sum(y)
}

